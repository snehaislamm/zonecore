#!/usr/bin/env python3
"""Requirements traceability: requirements.csv  <->  @verifies tags in tests.

usage: trace.py [--out docs/traceability.md] [--strict]

--strict exits non-zero if any requirement has no verifying test, or a test
references an unknown requirement (used as a CI gate).
"""
from __future__ import annotations

import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TAG = re.compile(r"@verifies((?:\s+REQ-[A-Z]+-\d+)+)")
REQ = re.compile(r"REQ-[A-Z]+-\d+")
C_TEST = re.compile(r"static void (test_\w+)\(void\)")
PY_TEST = re.compile(r"def (test_\w+)\(")


def scan() -> dict[str, list[str]]:
    hits: dict[str, list[str]] = defaultdict(list)
    for path in sorted((ROOT / "tests").rglob("*")):
        if path.suffix not in (".c", ".py"):
            continue
        lines = path.read_text().splitlines()
        kind = "unit" if path.suffix == ".c" else "SIL"
        pat = C_TEST if path.suffix == ".c" else PY_TEST
        for i, line in enumerate(lines):
            m = TAG.search(line)
            if not m:
                continue
            # the test the tag belongs to: next C definition below / enclosing def above
            name = "?"
            rng = range(i, min(i + 3, len(lines))) if path.suffix == ".c" else range(i, max(i - 3, -1), -1)
            for j in rng:
                if mm := pat.search(lines[j]):
                    name = mm[1]
                    break
            for req in REQ.findall(m[1]):
                hits[req].append(f"{kind}: `{path.relative_to(ROOT).as_posix()}::{name}`")
    return hits


def main(argv: list[str]) -> int:
    reqs = list(csv.DictReader((ROOT / "requirements" / "requirements.csv").open()))
    hits = scan()
    known = {r["id"] for r in reqs}
    unknown = sorted(set(hits) - known)
    missing = [r["id"] for r in reqs if r["id"] not in hits]

    out = ["# Requirements traceability matrix", "",
           "Generated by `tools/trace.py` from `requirements/requirements.csv` and `@verifies` tags. Do not edit.", "",
           f"**{len(reqs) - len(missing)}/{len(reqs)} requirements verified** "
           f"({sum(len(v) for v in hits.values())} test links).", "",
           "| ID | ASIL | Requirement | Verified by |", "|---|---|---|---|"]
    for r in reqs:
        tests = "<br>".join(sorted(set(hits.get(r["id"], [])))) or "**NOT VERIFIED**"
        out.append(f"| {r['id']} | {r['asil']} | {r['requirement']} | {tests} |")
    if unknown:
        out += ["", "## Unknown requirement IDs referenced by tests", ""] + [f"- {u}" for u in unknown]

    if "--out" in argv:
        dst = ROOT / argv[argv.index("--out") + 1]
        dst.write_text("\n".join(out) + "\n")
        print(f"wrote {dst.relative_to(ROOT)}")
    print(f"{len(reqs) - len(missing)}/{len(reqs)} requirements verified")
    for m in missing:
        print(f"  NOT VERIFIED: {m}")
    for u in unknown:
        print(f"  UNKNOWN: {u}")
    return 1 if ("--strict" in argv and (missing or unknown)) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
